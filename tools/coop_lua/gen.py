"""Generates the co-op test scripts in src/lua/ from tools/coop_lua/lib.lua.

Each script is self-contained (lib + one action) so it can be run with a single
`luafile <name>` console command. Re-run after editing lib.lua:
    python tools/coop_lua/gen.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / "src" / "lua"
LIB = (HERE / "lib.lua").read_text(encoding="utf-8")

ACTIONS = {
    "coop_status": ("Both PCs. Prints this PC's hero and the co-op partner (henchman) as the game sees them.", '''
print("[coop] status: multiplayer=" .. tostring(CoopHero.Try("IsMultiplayerGame", IsMultiplayerGame)) ..
  " localcoop=" .. tostring(CoopHero.Try("IsLocalCoopGame", Multiplayer.IsLocalCoopGame)))
CoopHero.Describe("hero", CoopHero.Try("GetPlayerHero", GetPlayerHero))
CoopHero.Describe("henchman", CoopHero.Try("GetPlayerHenchman", GetPlayerHenchman))
'''),
    "coop_exp1_body": ("Experiment 1, HOST PC, partner in game. Turns the henchman into a full hero body (CreatureHero).", '''
local hench = CoopHero.Try("GetPlayerHenchman", GetPlayerHenchman)
if not hench or not hench:IsAlive() then
  print("[coop] exp1: no live henchman - is your partner in your game?")
else
  CoopHero.Try("ChangePlayerEntityType", Player.ChangePlayerEntityType, hench, "CreatureHero")
  print("[coop] exp1: henchman changed to CreatureHero; partner: does your character look like a normal hero now?")
  CoopHero.Describe("henchman", GetPlayerHenchman())
end
'''),
    "coop_exp2_look": ("Experiment 2, HOST PC, partner in game. Puts a hat on the henchman and makes it fatter.", '''
local hench = CoopHero.Try("GetPlayerHenchman", GetPlayerHenchman)
if not hench or not hench:IsAlive() then
  print("[coop] exp2: no live henchman - is your partner in your game?")
else
  CoopHero.Try("AddAndReplaceItemOfType", AppearanceModifierManager.AddAndReplaceItemOfType, hench, "ObjectClothingHatMascotM")
  CoopHero.Try("ModifyFat", Stats.ModifyFat, hench, 0.5)
  print("[coop] exp2: gave the henchman a mascot hat and +0.5 fat; partner: do you see both?")
  CoopHero.Describe("henchman", hench)
end
'''),
    "coop_exp3_mirror": ("Experiment 3, HOST PC, partner in game. Copies the host hero's body, stats, clothes and weapons onto the henchman (tests the full apply step).", '''
local hero = CoopHero.Try("GetPlayerHero", GetPlayerHero)
local hench = CoopHero.Try("GetPlayerHenchman", GetPlayerHenchman)
if not hench or not hench:IsAlive() then
  print("[coop] exp3: no live henchman - is your partner in your game?")
else
  local profile = CoopHero.Capture(hero)
  print("[coop] exp3: host profile " .. CoopHero.Serialize(profile))
  CoopHero.Apply(hench, profile)
  print("[coop] exp3: applied the host's look to the henchman; partner: do you now look like the host's hero?")
  CoopHero.Describe("henchman", hench)
end
'''),
    "coop_capture": ("Experiment 4, JOINER PC, before joining and again after leaving. Prints this hero's profile (COOPHERO line) - stats, XP, clothes, weapons.", '''
local hero = CoopHero.Try("GetPlayerHero", GetPlayerHero)
if hero then print(CoopHero.Serialize(CoopHero.Capture(hero))) end
'''),
    "coop_capture2": ("Feature 001 rig check. Prints this hero and player 2 as profile v2 lines, then parses each back and prints it again (the two lines must match).", '''
for _, who in ipairs({{"hero", GetPlayerHero}, {"player2", GetPlayerHenchman}}) do
  local e = CoopHero.Try(who[1], who[2])
  if e and e:IsAlive() then
    local line = CoopHero.SerializeV2(CoopHero.Capture(e), 0)
    print("[coop] capture2 " .. who[1])
    print(line)
    print("[coop] reparse " .. (CoopHero.SerializeV2(CoopHero.Parse(line), 0) == line and "same" or "DIFFERENT"))
  else
    print("[coop] capture2 " .. who[1] .. ": none")
  end
end
'''),
}

def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (desc, body) in ACTIONS.items():
        text = f"-- {name}.lua (generated by tools/coop_lua/gen.py - edit lib.lua / gen.py instead)\n"
        text += f"-- {desc}\n-- Run from the backtick console: luafile {name}\n\n"
        text += LIB.rstrip() + "\n\n-- action\n" + body.lstrip()
        (OUT / f"{name}.lua").write_text(text, encoding="utf-8", newline="\n")
    for i in range(8):
        (OUT / f"console_{i}.lua").write_text(
            "-- Slot for the `lua` console command (rewritten by the game exe).\n",
            encoding="utf-8", newline="\n")
    # The plain library, read by the game exe to build apply chunks
    # (src/core/fable2_coop_hero.h). Running it on its own only defines CoopHero.
    (OUT / "coop_lib.lua").write_text(
        "-- coop_lib.lua (generated by tools/coop_lua/gen.py - edit lib.lua instead)\n"
        "-- Defines CoopHero; read by the game exe to build co-op apply chunks.\n\n" + LIB,
        encoding="utf-8", newline="\n")
    print("wrote", len(ACTIONS), "scripts, coop_lib.lua and 8 console slots to", OUT)

if __name__ == "__main__":
    main()
